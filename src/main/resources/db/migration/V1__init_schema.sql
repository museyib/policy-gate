create table app_user
(
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null,
    password_hash varchar(255) not null,
    display_name  varchar(120) not null,
    user_type varchar(10),
    root_user boolean,
    created_at    timestamp    not null,
    updated_at    timestamp,
    created_by    varchar(255),
    updated_by    varchar(255),
    constraint uk_user_email unique (email)
);

create table refresh_token
(
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null,
    token_hash varchar(64) not null,
    expires_at timestamp   not null,
    revoked_at timestamp,
    created_at timestamp   not null,
    updated_at timestamp,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_refresh_token_hash unique (token_hash),
    constraint fk_refresh_token_user foreign key (user_id) references app_user (id)
);

create index idx_refresh_token_user_id on refresh_token (id);

create table app_role
(
    id   bigint generated by default as identity primary key,
    name varchar(100),
    created_at timestamp   not null,
    updated_at timestamp,
    created_by varchar(255),
    updated_by varchar(255)
);

create table user_role
(
    user_id bigint references app_user(id),
    role_id bigint references  app_role(id),
    constraint uk_user_role unique (user_id, role_id)
);

create table resource
(
    id   bigint generated by default as identity primary key,
    code varchar(50) not null,
    name varchar(100),
    created_at timestamp   not null,
    updated_at timestamp ,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_resource_code unique (code)
);

create table resource_action
(
    resource_id bigint references resource(id),
    action varchar(20),
    constraint uk_resource_action unique (resource_id, action)
);

create table app_permission
(
    id   bigint generated by default as identity primary key,
    user_id bigint references app_user(id),
    role_id bigint references  app_role(id),
    resource_id bigint references resource(id),
    action varchar(20)
)